from __future__ import annotations

import dataclasses


# `pos_in_file` marks a position within the position space generated by the position tracker
# (`archon.text_pos.TextPosTracker`). If this is a position of a token produced by the
# tokenizer (`._tokenize.Tokenizer`), the position tracker is the one that was passed in the
# construction of the tokenizer. The position space does not include honored splicing
# connectors (backslash + newline). This means that the position space runs continuously
# across logical lines, not physical lines. This is necessary in order to allow for accurate
# position interpolation across the token texts, which do not include the splicing
# connectors. Splicing connectors cannot be dealt with in the same way as resolved
# free-standing UCNs, because such UCNs must be restored by `#x`, but splicing connectors
# must not.
#
@dataclasses.dataclass(slots=True, frozen=True)
class Position:
    file_index:  int
    pos_in_file: int

    def shift(self, offset: int) -> Position:
        return Position(file_index = self.file_index, pos_in_file = self.pos_in_file + offset)
